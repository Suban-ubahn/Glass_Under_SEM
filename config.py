def output_folder(script_name, dataset=None):
    """
    Name of the folder under outputs/ in which a script writes: <script_name>_<dataset>
    (e.g. "run_d2min_zr50cu50_sim"), with `dataset` a key of DATASETS (default: the active
    dataset). The only place that defines this rule; utils.get_output_dir() and the scripts
    that read the results of other scripts use it. (A function in this
    constants module because scripts/pypty_reconstruct.py runs in an environment in which
    nothing but config can be imported.)
    """
    key = ACTIVE_DATASET if dataset is None else dataset
    if key not in DATASETS:
        raise KeyError(f"unknown dataset {key!r}; config.DATASETS has: {', '.join(DATASETS)}")
    return f"{script_name}_{key}"

