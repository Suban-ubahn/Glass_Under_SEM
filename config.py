# ------------------------------------------------------------
# Melt-quench MD  (md/, scripts/generate_md.py, slurm/run_md.sh)
#
# Produces the LAMMPS dump of DATASETS[MD_DATASET]["trajectory_file"] in data/.
# Species and LAMMPS type numbering come from that dataset entry (type_to_z), so
# the generated file is read back by the analysis with the same mapping.
#
# Protocol (every duration in ps, converted to steps with MD_TIMESTEP_FS):
#   1. soft start   NVE with limited displacement + Berendsen thermostat at MD_T_MELT_K
#   2. melt         NVT at MD_T_MELT_K, fixed cell (cubic, MD_DENSITY_G_CM3)
#   3. quench       NPT, MD_T_MELT_K -> MD_T_FINAL_K at MD_COOLING_RATE_K_PER_PS
#   4. anneal       NPT at MD_T_FINAL_K; the box of all later stages is the average
#                   box over the last MD_CELL_AVERAGE_PS of this stage
#   5. relax        NVT at MD_T_FINAL_K, fixed cell
#   6. production   MD_PRODUCTION_ENSEMBLE at MD_T_FINAL_K, fixed cell; the dump has
#                   MD_DUMP_N_FRAMES frames, MD_DUMP_EVERY_PS apart
# The cooling rate and the durations of 4 and 5 set how well relaxed the glass is.
# ------------------------------------------------------------

