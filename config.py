# One entry per dataset (a simulated structure, a ptychographic reconstruction, ...).
# Everything that depends on WHICH dataset is analysed lives here, so switching dataset
# = changing ACTIVE_DATASET (nothing else in the code base has to be touched).
#
# The KEY of an entry is the name of the dataset and also the tag of the output folders of
# every script: outputs/<script>_<key>/, e.g. outputs/run_d2min_zr50cu50_sim/ -- results of
# different datasets never share a folder. Name every dataset after what the data is:
#     <elements with their atomic percent, lowercase>_<kind>
#     zr50cu50_sim, al40o60_sim (a simulation), al40o60_ptycho (a measurement), ...
#
#   trajectory_file     LAMMPS dump (data/ is not tracked by git)
#   type_to_z           LAMMPS atom type -> atomic number
#   sample_name         label handed to the ptychographic reconstruction
#   peak_search_window  (optional) r-range (Å) in which the first peak of every
#                       partial g(r) is searched (utils.find_cutoff_from_gr); it
#                       has to contain the first-neighbour peak of EVERY species
#                       pair of the dataset. Default: (2.0, 4.0)
#
# Elements, pair types, cutoffs and plot labels are all derived from
# type_to_z; nothing downstream assumes a particular composition or a
# particular number of species.
#
# New dataset: add an entry here. A dataset generated by scripts/generate_md.py
# (see the MD_* block below) is described by the same entry: the generator
# writes its dump to trajectory_file and numbers its atom types as type_to_z.
# ------------------------------------------------------------

